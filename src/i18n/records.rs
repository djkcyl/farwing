//! Connection records and account events (`docs/connection-records.md`).
pub(crate) struct Records {
    pub page: &'static str,
    pub tab_connections: &'static str,
    pub tab_events: &'static str,
    pub empty: &'static str,
    pub loading: &'static str,
    pub load_more: &'static str,
    pub open: &'static str,
    pub guest: &'static str,
    /// An attempt that was not admitted (`RecordOutcome`).
    pub outcome: fn(&str) -> &'static str,
    /// How a visitor was admitted.
    pub admission: fn(&str) -> &'static str,
    pub relation: fn(&str) -> &'static str,
    pub purpose: fn(&str) -> &'static str,
    pub route: fn(&str) -> &'static str,
    pub end_reason: fn(&str) -> &'static str,
    pub direct: &'static str,
    pub web: &'static str,
    pub app: &'static str,
    pub time: &'static str,
    pub ended: &'static str,
    pub source: &'static str,
    pub path: &'static str,
    pub picture: &'static str,
    pub fps: fn(&str) -> String,
    pub rtt: fn(u32) -> String,
    pub stalls: fn(u32) -> String,
    pub reconnects: fn(u32) -> String,
    pub control: &'static str,
    pub controlled: &'static str,
    pub view_only: &'static str,
    pub camera: &'static str,
    pub camera_viewed: &'static str,
    pub files: &'static str,
    pub upload: &'static str,
    pub download: &'static str,
    pub file_outcome: fn(&str) -> &'static str,
    pub more_files: fn(u32) -> String,
    pub ports: &'static str,
    pub duration_hours: fn(u64, u64) -> String,
    pub duration_minutes: fn(u64) -> String,
    pub duration_seconds: fn(u64) -> String,
    /// An account event (`AccountEvent::kind`); empty when unknown.
    pub event: fn(&str) -> &'static str,
    pub failed: &'static str,
    pub by: fn(&str) -> String,
    pub power_action: fn(&str) -> &'static str,
    pub previous: fn(&str) -> String,
    pub friend: fn(&str) -> String,
    pub other_device: fn(&str) -> String,
}

